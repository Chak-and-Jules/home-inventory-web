import { test, expect, type Page } from '@playwright/test';
import en from '../src/lib/i18n/locales/en/common.json';
import tr from '../src/lib/i18n/locales/tr/common.json';
import { mockGuideApi, introduction } from './guide-api';
async function signIn(page: Page, copy: typeof en) {
  await page.goto('/login');
  await page.getByLabel(copy.auth.emailAddress).fill('ui-test@example.test');
  await page.getByLabel(copy.auth.password, { exact: true }).fill('fixture-password');
  await page.getByRole('button', { name: copy.auth.signIn, exact: true }).click();
  await expect(page.getByRole('heading', { name: 'UI Test Home' })).toBeVisible();
}
test('first setup resumes after failure and ends on the saved dashboard entry', async ({ page }, info) => {
  const copy = info.project.name.startsWith('tr') ? tr : en;
  const { state, controls } = await mockGuideApi(page, info.project.name.split('-')[0], { empty: true });
  await signIn(page, copy);
  await page.getByRole('button', { name: copy.guides.start, exact: true }).click();
  await expect(page).toHaveURL(`/guides/${introduction}`);
  await expect(page.getByText(copy.guides.homeHelp)).toBeVisible();
  await page.getByRole('button', { name: copy.guides.next, exact: true }).click();
  await expect(page.getByText(copy.guides.categoryHelp)).toBeVisible();
  await page.getByLabel(copy.ui.nameRequired).fill('Guide rice');
  await page.getByLabel(copy.ui.sizeUnitRequired).selectOption('kg');
  await page.getByRole('button', { name: copy.guides.saveDefinition, exact: true }).click();
  await expect(page.getByText('Guide rice', { exact: true })).toBeVisible();
  controls.failStockOnce = true;
  await page.getByLabel(copy.ui.quantity, { exact: true }).fill('2.5');
  await page.getByRole('button', { name: copy.guides.saveStock, exact: true }).click();
  await expect(page.getByText(copy.guides.saveFailed)).toBeVisible();
  expect(state.definitions).toHaveLength(1); expect(state.inventory).toHaveLength(0);
  await page.reload();
  await expect(page.getByText('Guide rice', { exact: true })).toBeVisible();
  expect(state.definitions).toHaveLength(1);
  await page.getByLabel(copy.ui.quantity, { exact: true }).fill('2.5');
  await page.getByRole('button', { name: copy.guides.saveStock, exact: true }).click();
  await expect(page).toHaveURL('/');
  await expect(page.getByRole('row').filter({ hasText: 'Guide rice' })).toBeVisible();
  await expect(page.getByText(copy.guides.dashboardHelp)).toBeVisible();
  expect(state.inventory[0].Quantity).toBe(2500);
  expect(controls.guide.status).toBe('in_progress');
  expect(await page.evaluate(() => document.documentElement.scrollWidth <= window.innerWidth)).toBe(true);
  await page.screenshot({ path: info.outputPath('guide-dashboard.png'), fullPage: true });
  await page.getByRole('button', { name: copy.guides.finish, exact: true }).click();
  await expect(page.getByRole('button', { name: copy.guides.finish, exact: true })).toHaveCount(0);
  expect(controls.guide.status).toBe('completed'); expect(controls.mobileOutcome).toBe('completed');
});
test('existing users can defer, reuse stock, and restore only the web tutorial', async ({ page }, info) => {
  const copy = info.project.name.startsWith('tr') ? tr : en;
  const { state, controls } = await mockGuideApi(page, info.project.name.split('-')[0]);
  await signIn(page, copy);
  await page.getByRole('button', { name: copy.guides.later, exact: true }).click();
  await expect(page.getByRole('button', { name: copy.guides.start, exact: true })).toHaveCount(0);
  expect(controls.guide.status).toBe('available'); expect(controls.mobileOutcome).toBe('available');
  await page.goto('/profile');
  await page.getByRole('button', { name: copy.guides.start, exact: true }).click();
  await page.getByRole('button', { name: copy.guides.next, exact: true }).click();
  await page.getByLabel(copy.guides.existingStock).selectOption('seed-inventory');
  await page.getByRole('button', { name: copy.guides.useStock, exact: true }).click();
  await expect(page).toHaveURL('/');
  await page.getByRole('button', { name: copy.guides.finish, exact: true }).click();
  await expect(page.getByRole('button', { name: copy.guides.finish, exact: true })).toHaveCount(0);
  await page.goto('/profile');
  await page.getByRole('button', { name: copy.guides.restore, exact: true }).click();
  await expect(page.getByText(copy.guides.homeHelp)).toBeVisible();
  expect(controls.guide.checkpoint.restored).toBe(true); expect(controls.mobileOutcome).toBe('completed');
  await page.reload(); await expect(page.getByText(copy.guides.homeHelp)).toBeVisible();
  await page.getByRole('button', { name: copy.guides.skip, exact: true }).click();
  await expect(page).toHaveURL('/');
  expect(controls.mobileOutcome).toBe('skipped');
  expect(state.definitions).toHaveLength(1); expect(state.inventory).toHaveLength(1);
  expect(controls.posts.filter(body => ['create_definition', 'create_inventory'].includes(body.action as string))).toHaveLength(0);
});
